import type { DescriptionInput, DescriptionProvider } from "./provider.ts";

/** Deterministic stand-in used when GEMINI_API_KEY is not set (local dev, tests, reviewers). */
export class MockProvider implements DescriptionProvider {
  readonly name = "mock" as const;

  async generate({ name, category, priceCents }: DescriptionInput): Promise<string> {
    const price = (priceCents / 100).toFixed(2);
    return `${name} is a ${category.toLowerCase()} offering designed to help teams get more done. Priced at $${price}, it fits easily into an existing workflow. (Draft generated by the built-in mock; set GEMINI_API_KEY for real AI output.)`;
  }
}
